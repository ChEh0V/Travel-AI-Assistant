let lastCity = null;

function mockReply(text) {
  const q = text.toLowerCase();
  const city = CITIES.find(c => c.keys.some(k => q.includes(k))) || null;
  if (city) lastCity = city;
  const c = city || lastCity;

  if (c && /бесплат/.test(q)) return "Бесплатно (" + c.name + "):\n" + c.free;
  if (c && /(маршрут|план|дн|день)/.test(q)) return "Маршрут (" + c.name + "):\n" + c.plan + "\n\nХотите, расскажу, что из этого бесплатно?";
  if (city) return "Что посмотреть (" + c.name + "):\n" + c.sights + "\n\nМогу составить маршрут по дням или подсказать бесплатные места.";

  const g = GENERIC.find(g => g.keys.some(k => q.includes(k)));
  if (g) return g.text;

  return "Пока я лучше всего знаю Рим, Париж, Токио и Стамбул. Спросите, например: «Что посмотреть в Париже?» или «Маршрут по Токио на 2 дня».\n\nОбщий совет: выберите 2–3 главных места в день, остальное время оставьте на прогулки.";
}

// Имитирует задержку сети, чтобы интерфейс вёл себя как с настоящим API.
function getReply(messages) {
  const last = messages[messages.length - 1].content;
  return new Promise(resolve => setTimeout(() => resolve(mockReply(last)), 600 + Math.random() * 600));
}
